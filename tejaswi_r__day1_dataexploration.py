import pandas as pd
import matplotlib.pyplot as plt
import seaborn as sns
data = {
    "Hours_Studied": [2, 5, 3, 7, 1, 6, 4, 8, 5, 3],
    "Attendance": [60, 90, 75, 95, 50, 88, 80, 98, 85, 70],
    "Previous_Score": [45, 70, 55, 82, 40, 78, 65, 90, 72, 58],
    "Final_Score": [42, 76, 58, 88, 35, 82, 68, 94, 79, 60]
}
df = pd.DataFrame(data)
print("COMPLETE DATASET")
print(df)
print("\nFIRST FIVE ROWS")
print(df.head())
print("\nDATASET SHAPE")
print(df.shape)
print("\nDATA TYPES")
print(df.dtypes)
print("\nMISSING VALUES")
print(df.isnull().sum())
print("\nSTATISTICAL SUMMARY")
print(df.describe())
Q1 = df["Final_Score"].quantile(0.25)
Q3 = df["Final_Score"].quantile(0.75)
IQR = Q3 - Q1
lower_limit = Q1 - 1.5 * IQR
upper_limit = Q3 + 1.5 * IQR
outliers = df[
    (df["Final_Score"] < lower_limit) |
    (df["Final_Score"] > upper_limit)
]
print("\nUNUSUAL VALUES")
print(outliers)
plt.figure(figsize=(8, 5))
sns.boxplot(y=df["Final_Score"])
plt.title("Box Plot of Student Final Scores")
plt.ylabel("Final Score")
plt.show()
print("\nTHREE OBSERVATIONS")
print("1. Final scores range from 35 to 94.")
print("2. Students who studied more hours generally achieved higher scores.")
print("3. Higher attendance is generally associated with better scores.")
print("Data analysis helps us understand student performance.")
print("Study hours and attendance may influence final scores.")

